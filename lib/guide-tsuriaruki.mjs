// 記事の図。撮影地の近くの観測点の干満差を大きい順に並べる。
export function tsuriaruikiVisual(figure) {
  const rows = AREAS.flatMap(a => a[3]).sort((x, y) => y[1] - x[1]);
  const max = rows[0][1];
  const bars = rows.map(([n, v]) => `<div class="visual-bar-row"><span>${esc(n)}</span><div class="visual-bar-track"><i style="width:${(v / max * 100).toFixed(1)}%"></i></div><b>${v}cm</b></div>`).join('');
  return `<h2>撮影地の近くの観測点の干満差</h2>${figure('撮影地の近くの観測点の干満差', `<div class="visual-bars">${bars}</div>`,
    '気象庁 2026年潮位表の推算値から、各観測点の1日の干満差を通年で平均した値（cm）。同じ「水深を測る」作業でも、潮位で補正する量が場所によってこれだけ違います。')}`;
}

