// 地方ごとの潮の大きさ。national.regions = [{ r, pf }]
function regionRangeTable(nat) {
  const rows = [...(nat?.regions || [])].sort((a, b) => b.pf.avg - a.pf.avg);
  if (rows.length < 2) return '';
  return `<div class="tw"><table class="prefsum">
    <thead><tr><th>地方</th><th>平均の干満差</th><th>大潮のころ</th><th>小潮のころ</th><th>満潮1回の日</th></tr></thead>
    <tbody>${rows.map(x => `<tr>
      <th scope="row"><a href="${attr(paths.region(x.r))}">${esc(x.r.name)}</a></th>
      <td>${x.pf.avg} cm</td><td>${x.pf.spring} cm</td><td>${x.pf.neap} cm</td><td>${x.pf.diurnalPct}%</td>
    </tr>`).join('')}</tbody>
  </table></div>
  <p class="note">気象庁 ${nat.year}年 潮位表の推算値から、各地方の公式観測点を通年で集計した値です。平均の干満差が大きい順。</p>`;
}

// 地方ごとの「日中の干潮が最も低くなりやすい月」
function regionSeasonTable(nat) {
  const rows = [...(nat?.regions || [])].filter(x => x.pf.dayLowMonthMode);
  if (rows.length < 2) return '';
  return `<div class="tw"><table class="prefsum">
    <thead><tr><th>地方</th><th>大潮のころの干満差</th><th>日中の干潮が最も低くなる月（最も多い月）</th></tr></thead>
    <tbody>${rows.map(x => `<tr>
      <th scope="row"><a href="${attr(paths.region(x.r))}">${esc(x.r.name)}</a></th>
      <td>${x.pf.spring} cm</td>
      <td>${x.pf.dayLowMonthMode}月（${x.pf.dayLowMonthCount[x.pf.dayLowMonthMode - 1]}/${x.pf.n}地点）</td>
    </tr>`).join('')}</tbody>
  </table></div>
  <p class="note">気象庁 ${nat.year}年 潮位表の推算値で、観測点ごとに日中（6〜18時）の干潮が年間で最も低くなる月を求め、地方ごとに最も多かった月を示しています。</p>`;
}

function seasonSentence(nat) {
  const pf = nat?.pf;
  if (!pf || !pf.n) return '';
  const top = topMonths(pf.dayLowMonthCount, 3).map(x => `${x.m}月（${x.c}地点）`).join('、');
  const ss = monthShare(pf.dayLowMonthCount, 3, 8);
  return `<p>気象庁の${nat.year}年の潮位表で全国の公式観測点${pf.n}地点を調べると、日中（6〜18時）の干潮が年間で最も低くなる月は、多い順に${top}でした。3月から8月のいずれかになった地点は${ss}地点（${Math.round(ss / pf.n * 100)}%）です。</p>`;
}

