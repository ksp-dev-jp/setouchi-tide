export function activityBySlug(slug) {
  return ACTIVITIES.find(a => a.slug === slug);
}

function activityTrail(a) {
  return [
    { name: '全国', href: paths.home(), abs: abs.home() },
    { name: a.title, href: paths.activity(a.slug), abs: abs.activity(a.slug) },
  ];
}

