// 季節の干潮の記事に入れる全国集計。nat は build.mjs の national。
function seasonData(nat) {
  const pf = nat?.pf;
  if (!pf || !pf.n) return '';
  const fmt = arr => arr.map(x => `${x.m}月（${x.c}地点）`).join('、');
  const day = monthShare(pf.dayLowMonthCount, 3, 8);
  const night = monthShare(pf.nightLowMonthCount, 9, 2);
  const dayPct = Math.round(day / pf.n * 100), nightPct = Math.round(night / pf.n * 100);
  const rows = pf.dayLowMonthCount.map((c, i) =>
    `<tr><th scope="row">${i + 1}月</th><td>${c}</td><td>${pf.nightLowMonthCount[i]}</td></tr>`).join('');
  return `<h2>全国${pf.n}地点の集計</h2>
<p>しおどきで、気象庁の${nat.year}年の潮位表（推算値）から全国の公式観測点${pf.n}地点について「日中（6〜18時）の干潮が年間で最も低くなる月」を調べると、多い順に${fmt(topMonths(pf.dayLowMonthCount))}でした。3月から8月のいずれかになった地点は${day}地点（${dayPct}%）です。</p>
<p>反対に「夜間（18時〜翌6時）の干潮が最も低くなる月」は、多い順に${fmt(topMonths(pf.nightLowMonthCount))}で、9月から2月のいずれかになった地点は${night}地点（${nightPct}%）でした。${dayPct >= 60 && nightPct >= 60
    ? '昼は春から夏、夜は秋から冬という傾向が、全国の大半の地点で実際の推算値に表れています。'
    : 'ただし地点による違いも大きく、この傾向がすべての地点に当てはまるわけではありません。'}</p>
<div class="tw"><table class="prefsum">
  <thead><tr><th>月</th><th>日中の干潮が最も低くなる地点数</th><th>夜間の干潮が最も低くなる地点数</th></tr></thead>
  <tbody>${rows}</tbody>
</table></div>
<p class="note">各観測点で、月ごとに日中・夜間それぞれの干潮の最低潮位を求め、年間で最も低い月を数えています。潮位は地点ごとの基準面からの高さなので、比べているのは同じ地点の中での月ごとの違いです。</p>`;
}

